export const searchColleges = (query, filters = {}) => {
  let results = [...kathmanduColleges]
  
  // Filter by search query
  if (query) {
    const lowerQuery = query.toLowerCase()
    results = results.filter(college => 
      college.name.toLowerCase().includes(lowerQuery) ||
      college.location.toLowerCase().includes(lowerQuery) ||
      college.area.toLowerCase().includes(lowerQuery) ||
      college.type.toLowerCase().includes(lowerQuery)
    )
  }
  
  // Filter by area
  if (filters.area) {
    results = results.filter(college => college.area === filters.area)
  }
  
  // Filter by type
  if (filters.type) {
    results = results.filter(college => college.type === filters.type)
  }
  
  return results
}

// Get college by name
export const getCollegeByName = (name) => {
  return kathmanduColleges.find(c => c.name === name)
}

// Get colleges near a specific area
export const getCollegesByArea = (area) => {
  return kathmanduColleges.filter(c => c.area === area || c.location.includes(area))
}

// Format college display string
export const formatCollegeDisplay = (college) => {
  if (typeof college === 'string') {
    const found = getCollegeByName(college)
    if (found) {
      return `${found.name} - ${found.location}`
    }
    return college
  }
  return `${college.name} - ${college.location}`
}

// Get college count by area
export const getCollegeCountByArea = () => {
  const counts = {}
  collegeAreas.forEach(area => {
    counts[area] = kathmanduColleges.filter(c => c.area === area).length
  })
  return counts
}

// Get college count by type
export const getCollegeCountByType = () => {
  const counts = {}
  collegeTypes.forEach(type => {
    counts[type] = kathmanduColleges.filter(c => c.type === type).length
  })
  return counts
}

export default kathmanduColleges
